// Generate src/generated/ from openapi/openapi.json.
//
//   node scripts/generate.mjs           write the files
//   node scripts/generate.mjs --check   exit 1 when the committed files are out of date (CI)
//
// - schema.ts: the types of every path, operation and schema, written by openapi-typescript (binary fields are Blob).
// - operations.ts: one method per operationId (camelCase) on GeneratedOperations, typed by indexing schema.ts.
//   Every call goes through this.request (hand-written in src/client.ts): auth, retries, idempotency key, errors.
//
// The spec is produced by the backend (manage.py spectacular --format openapi-json); see the README.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import ts from "typescript";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SPEC = join(ROOT, "openapi", "openapi.json");
const OUT = join(ROOT, "src", "generated");
const METHODS = ["get", "post", "put", "patch", "delete"];
const HEADER = "// Generated by scripts/generate.mjs from openapi/openapi.json. Do not edit by hand.\n";

// POSTs that spend money without a 402 among their answers (a card charge). Every POST that can answer 402
// (insufficient funds) is paid as well; both get an Idempotency-Key.
const EXTRA_PAID = new Set(["purchase_credits"]);

// Paid POSTs whose server replays the first answer for a repeated Idempotency-Key (24 h), so retrying one after a
// 5xx or a dropped connection cannot start or charge a second job. Every other POST is retried on 429 only.
// Source: backend public_apis/v2/lifecycle.py (create, clone, translate) and public_apis/video_generation_views/*
// (the v1 creators), which call public_apis.idempotency.
const REPLAYS_IDEMPOTENCY_KEY = new Set([
  "create_video",
  "clone_video",
  "translate_video",
  "idea_to_video",
  "script_to_video",
  "blog_to_video",
  "audio_to_video",
  "agentic_video",
]);

const camel = (s) =>
  s
    .split("_")
    .filter(Boolean)
    .map((part, i) => (i === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join("");
const q = (s) => JSON.stringify(s);
const refName = (ref) => ref.slice(ref.lastIndexOf("/") + 1);

function resolve(spec, schema) {
  let s = schema || {};
  while (s.$ref) s = spec.components.schemas[refName(s.$ref)];
  return s;
}

function jsdoc(lines, indent) {
  const text = lines
    .filter(Boolean)
    .join("\n\n")
    .replaceAll("*/", "*\\/")
    .split("\n")
    .map((l) => `${indent} *${l ? " " + l : ""}`.trimEnd());
  return [`${indent}/**`, ...text, `${indent} */`];
}

function bodyKind(spec, op) {
  const rb = op.requestBody;
  if (!rb) return null;
  const types = Object.keys(rb.content);
  const first = types[0];
  const props = resolve(spec, rb.content[first].schema).properties || {};
  const hasFile = Object.values(props).some((p) => resolve(spec, p).format === "binary");
  if (first === "multipart/form-data" && (hasFile || !types.includes("application/json"))) return "multipart";
  if (types.includes("application/json")) return "json";
  return "multipart";
}

function schemaTs(ast) {
  return HEADER + "/* eslint-disable */\n" + astToString(ast);
}

async function renderSchema(spec) {
  const blob = ts.factory.createTypeReferenceNode(ts.factory.createIdentifier("Blob"));
  const nullable = ts.factory.createUnionTypeNode([blob, ts.factory.createLiteralTypeNode(ts.factory.createNull())]);
  const ast = await openapiTS(spec, {
    // A request field with a default is optional to send (answers list their always-present keys in `required`).
    defaultNonNullable: false,
    transform(schemaObject) {
      if (schemaObject.format !== "binary") return undefined;
      const t = schemaObject.type;
      return (Array.isArray(t) && t.includes("null")) || schemaObject.nullable ? nullable : blob;
    },
  });
  return schemaTs(ast);
}

function renderOperations(spec) {
  const out = [
    HEADER,
    'import type { operations } from "./schema.js";',
    'import type { OperationMeta, RequestArgs, RequestOptions } from "../types.js";',
    "",
    "type Ops = operations;",
    "",
    "export abstract class GeneratedOperations {",
    "  protected abstract request<T>(op: OperationMeta, args: RequestArgs): Promise<T>;",
    "",
  ];
  const table = [];
  const ids = [];
  for (const [path, item] of Object.entries(spec.paths)) {
    for (const method of METHODS) {
      const op = item[method];
      if (!op) continue;
      const id = op.operationId;
      ids.push(id);
      const name = camel(id);
      const kind = bodyKind(spec, op);
      const responses = op.responses || {};
      const paid = method === "post" && ("402" in responses || EXTRA_PAID.has(id));
      const params = [...(item.parameters || []), ...(op.parameters || [])];
      const pathParams = params.filter((p) => p.in === "path");
      const queryParams = params.filter((p) => p.in === "query");
      const queryNames = queryParams.map((p) => p.name);
      const bodyProps = kind ? Object.keys(resolve(spec, op.requestBody.content[kind === "json" ? "application/json" : Object.keys(op.requestBody.content)[0]].schema).properties || {}) : [];
      const wrapped = bodyProps.some((p) => queryNames.includes(p));
      const contentType = kind === "json" ? "application/json" : kind ? Object.keys(op.requestBody.content).find((c) => c.startsWith("multipart")) || Object.keys(op.requestBody.content)[0] : null;

      table.push(
        `  ${id}: { operationId: ${q(id)}, method: ${q(method.toUpperCase())}, path: ${q(path)}, ` +
          `body: ${kind ? q(kind) : "null"}, query: ${q(queryNames)}, wrapped: ${wrapped}, paid: ${paid}, ` +
          `replaysIdempotencyKey: ${REPLAYS_IDEMPOTENCY_KEY.has(id)}, deprecated: ${!!op.deprecated} },`,
      );

      const bodyType = kind ? `NonNullable<Ops[${q(id)}]["requestBody"]>["content"][${q(contentType)}]` : null;
      const queryType = queryParams.length ? `NonNullable<Ops[${q(id)}]["parameters"]["query"]>` : null;
      let paramsType = null;
      if (wrapped) paramsType = `{ body: ${bodyType}; query${queryParams.some((p) => p.required) ? "" : "?"}: ${queryType} }`;
      else paramsType = [bodyType, queryType].filter(Boolean).join(" & ") || null;
      const paramsRequired = (kind && op.requestBody.required) || queryParams.some((p) => p.required);

      const ok = Object.entries(responses).filter(([code, r]) => code.startsWith("2") && r.content && r.content["application/json"]);
      let ret;
      if (ok.length) ret = ok.map(([code]) => `Ops[${q(id)}]["responses"][${q(code)}]["content"]["application/json"]`).join(" | ");
      else if (Object.keys(responses).some((c) => c.startsWith("3"))) ret = "string";
      else ret = "void";

      const args = pathParams.map((p) => `${camel(p.name)}: Ops[${q(id)}]["parameters"]["path"][${q(p.name)}]`);
      if (paramsType) args.push(`params${paramsRequired ? "" : "?"}: ${paramsType}`);
      args.push("options?: RequestOptions");

      const doc = [op.summary, op.description, `\`${method.toUpperCase()} ${path}\``];
      if (paid) doc.push("Paid: sends an `Idempotency-Key` (`options.idempotencyKey`, or a new one reused across this call's retries).");
      if (op.deprecated) doc.push("@deprecated The API marks this operation deprecated.");
      out.push(...jsdoc(doc, "  "));
      out.push(`  ${name}(${args.join(", ")}): Promise<${ret}> {`);
      const pathObj = pathParams.map((p) => `${q(p.name)}: ${camel(p.name)}`).join(", ");
      out.push(
        `    return this.request(OPERATIONS.${id}, { path: { ${pathObj} }, params: ${paramsType ? "params" : "undefined"}, options });`,
      );
      out.push("  }", "");
    }
  }
  out.push("}", "");
  out.push("/** Every operation of the API, by operationId. */");
  out.push("export const OPERATIONS = {");
  out.push(...table);
  out.push("} as const satisfies Record<string, OperationMeta>;", "");
  out.push(`export const OPERATION_IDS = ${JSON.stringify(ids.sort(), null, 2)} as const;`, "");
  return out.join("\n");
}

const spec = JSON.parse(readFileSync(SPEC, "utf8"));
const files = {
  "schema.ts": await renderSchema(spec),
  "operations.ts": renderOperations(spec),
};
const check = process.argv.includes("--check");
const stale = [];
for (const [name, text] of Object.entries(files)) {
  const target = join(OUT, name);
  if (check) {
    if (!existsSync(target) || readFileSync(target, "utf8") !== text) stale.push(name);
  } else {
    mkdirSync(OUT, { recursive: true });
    writeFileSync(target, text);
  }
}
if (stale.length) {
  console.error(`out of date: ${stale.join(", ")} (run npm run generate)`);
  process.exit(1);
}
if (!check) console.log(`wrote ${Object.keys(files).length} files to src/generated`);
